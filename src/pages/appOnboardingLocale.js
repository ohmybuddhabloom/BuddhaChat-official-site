export const ONBOARDING_COPY = { en, 'zh-Hans': zhHans, 'zh-Hant': zhHant }

export function normalizeOnboardingLocale(value) {
  if (value === 'zh-Hant') return 'zh-Hant'
  if (value === 'zh-Hans') return 'zh-Hans'
  if (typeof value === 'string' && value.toLowerCase().startsWith('en')) return 'en'
  return 'zh-Hans'
}

export function getOnboardingCopy(locale) {
  return ONBOARDING_COPY[normalizeOnboardingLocale(locale)]
}

export function optionPairs(ids, labels) {
  return ids.map((id) => [id, labels[id]])
}

export function monthPairs(labels) {
  return labels.map((label, index) => [String(index + 1).padStart(2, '0'), label])
}

export const LEGACY_IMPROVEMENT_IDS = Object.fromEntries(
  IMPROVEMENT_IDS.map((id) => [zhHans.options.improvements[id], id]),
)

export const LEGACY_SUPPORT_IDS = Object.fromEntries(
  SUPPORT_IDS.map((id) => [zhHans.options.supports[id], id]),
)

export const LEGACY_MONTH_IDS = Object.fromEntries(
  [zhHans, zhHant, en].flatMap((copy) => monthPairs(copy.options.months).map(([id, label]) => [label, id])),
)
